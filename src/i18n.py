"""Idiomas da interface. Todos os rótulos de origem são escritos em português brasileiro.

O inglês é opcional; textos técnicos, seletores do jogo, IDs e chaves de
configuração não são traduzidos. Isso evita misturar conteúdos do jogo com
os textos que o aplicativo controla.
"""
from __future__ import annotations

LANGUAGES = {"pt_BR": "Português (Brasil)", "en": "English"}
DEFAULT_LANGUAGE = "pt_BR"
_language = DEFAULT_LANGUAGE


def set_language(code: str) -> str:
    global _language
    _language = code if code in LANGUAGES else DEFAULT_LANGUAGE
    return _language


def language() -> str:
    return _language


def t(text: str, **values) -> str:
    """Traduz um texto de origem pt-BR sem alterar argumentos formatados."""
    result = EN.get(text, text) if _language == "en" else text
    return result.format(**values) if values else result


def tip(key: str):
    """Ajuda contextual do controle no idioma selecionado."""
    from help_texts import HELP, HELP_EN
    return (HELP_EN if _language == "en" else HELP).get(key) or HELP.get(key)


